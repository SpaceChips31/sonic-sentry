def resolve_language(request: Request | None) -> str:
    if request is None:
        return "en"
    override = request.cookies.get("lv_language")
    if override in {"it", "en"}:
        return override
    browser = request.headers.get("accept-language", "").lower()
    return "it" if browser.startswith("it") else "en"


def translate(request: Request | None, key: str) -> str:
    if resolve_language(request) == "it":
        return ITALIAN.get(key, key)
    return key
